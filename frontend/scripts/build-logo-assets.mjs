// Writes the static copies of the ECTLogger logo from the one source,
// src/components/brand/logo.ts. Run from frontend/ after changing the art:
//
//   node scripts/build-logo-assets.mjs
//
// Outputs:
//   public/logo.svg                     favicon and apple-touch-icon (light mark)
//   ../docs/assets/logo.svg             canonical light mark
//   ../docs/assets/logo-dark.svg        canonical dark mark
//   ../docs/assets/lockup-light.svg     mark + wordmark for light backgrounds
//   ../docs/assets/lockup-dark.svg      mark + wordmark for dark backgrounds
//   ../backend/app/email/logo_svg.py    LOGO_SVG for email headers (light, 28 px)
import { buildSync } from 'esbuild';
import { writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const { outputFiles } = buildSync({
  entryPoints: [resolve(root, 'src/components/brand/logo.ts')],
  bundle: true, format: 'esm', write: false, platform: 'neutral',
});
const L = await import('data:text/javascript;base64,' + Buffer.from(outputFiles[0].text).toString('base64'));

const HEADER = '<!-- Generated by frontend/scripts/build-logo-assets.mjs from src/components/brand/logo.ts. Do not edit. -->\n';

const mark = (palette) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${L.LOGO_VIEWBOX}" width="256" height="256" role="img" aria-label="ECTLogger">${L.logoMarkMarkup(palette)}</svg>\n`;

// Lockup: the mark at 112 px, then the wordmark, as in the Claude Design file.
const lockup = (palette, colors) => {
  const s = 112 / 256;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 456.55 112" width="457" height="112" role="img" aria-label="ECTLogger">`
    + `<g transform="scale(${s})">${L.logoMarkMarkup(palette)}</g>`
    + `<g transform="translate(131.97 75.23)"><path fill="${colors.ect}" d="${L.WORDMARK_ECT_PATH}"/><path fill="${colors.logger}" d="${L.WORDMARK_LOGGER_PATH}"/></g>`
    + `</svg>\n`;
};

const out = {
  'public/logo.svg': HEADER + mark(L.LOGO_LIGHT),
  '../docs/assets/logo.svg': HEADER + mark(L.LOGO_LIGHT),
  '../docs/assets/logo-dark.svg': HEADER + mark(L.LOGO_DARK),
  '../docs/assets/lockup-light.svg': HEADER + lockup(L.LOGO_LIGHT, L.WORDMARK_LIGHT),
  '../docs/assets/lockup-dark.svg': HEADER + lockup(L.LOGO_DARK, L.WORDMARK_DARK),
  '../backend/app/email/logo_svg.py':
    '"""Generated by frontend/scripts/build-logo-assets.mjs from\nfrontend/src/components/brand/logo.ts. Do not edit; re-run the script.\n\n'
    + 'The light mark for email headers. Some mail clients (Gmail among them)\ndrop inline SVG, which is why the heading text never depends on it.\n"""\n\n'
    + 'LOGO_SVG = ' + JSON.stringify(L.logoMarkSvg(L.LOGO_LIGHT, 28, 'vertical-align:middle;margin-right:6px')) + '\n',
};

for (const [path, text] of Object.entries(out)) {
  writeFileSync(resolve(root, path), text);
  console.log('wrote', path);
}
